"""Set up the shared Remotion engine and create / register remake projects.

usage:
  new_project.py setup                 # copy the engine kit to D:\\VideoBlueprint\\remakes\\engine, npm install once
  new_project.py create <id>           # projects/<id>/ with a script.json template; prints the folder
  new_project.py register              # regenerate src/projects.ts from every projects/*/ having project.json + scenes.tsx

Every remake renders in ONE engine (one node_modules); a project = projects/<id>/ (script, recipe,
project.json, scenes.tsx, out/) + public/<id>/ (vo.mp3, music.wav, sfx/). Nothing is written to the
user's Remotion repo.
"""
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from rmcommon import ENGINE, SKILL  # noqa: E402

TEMPLATE = SKILL / "assets" / "engine"


def setup():
    ENGINE.mkdir(parents=True, exist_ok=True)
    for p in TEMPLATE.rglob("*"):
        rel = p.relative_to(TEMPLATE)
        dst = ENGINE / rel
        if p.is_dir():
            dst.mkdir(parents=True, exist_ok=True)
            continue
        if rel.as_posix() == "src/projects.ts" and dst.exists():
            continue  # keep the registry of existing projects
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(p, dst)  # kit files are always refreshed from the skill
    (ENGINE / "projects").mkdir(exist_ok=True)
    (ENGINE / "public").mkdir(exist_ok=True)
    if not (ENGINE / "node_modules" / "remotion").exists():
        print("[video-remake] npm install (first time, ~1-2 min)...", flush=True)
        subprocess.run(["npm.cmd", "install", "--no-audit", "--no-fund"], cwd=ENGINE, check=True)
    print(f"[video-remake] engine ready: {ENGINE}")


def create(pid):
    if not re.fullmatch(r"[a-z0-9][a-z0-9-]{1,60}", pid):
        sys.exit("project id: lowercase letters, digits and hyphens")
    d = ENGINE / "projects" / pid
    d.mkdir(parents=True, exist_ok=True)
    (d / "out").mkdir(exist_ok=True)
    tpl = SKILL / "assets" / "script.template.json"
    if not (d / "script.json").exists():
        s = json.loads(tpl.read_text(encoding="utf-8"))
        s["id"] = pid
        (d / "script.json").write_text(json.dumps(s, indent=2, ensure_ascii=False), encoding="utf-8")
    print(d)


def register():
    rows, imports = [], ["import type {Project, ProjectEntry} from './kit/types';"]
    for i, d in enumerate(sorted((ENGINE / "projects").iterdir())):
        if (d / "project.json").exists() and (d / "scenes.tsx").exists():
            imports.append(f"import p{i} from '../projects/{d.name}/project.json';")
            imports.append(f"import {{SCENES as s{i}}} from '../projects/{d.name}/scenes';")
            rows.append(f"  {{id: '{d.name}', project: p{i} as unknown as Project, scenes: s{i}}},")
    body = "// GENERATED by video-remake/scripts/new_project.py register - do not edit.\n" + "\n".join(imports) + \
        "\n\nexport const PROJECTS: ProjectEntry[] = [\n" + "\n".join(rows) + "\n];\n"
    (ENGINE / "src" / "projects.ts").write_text(body, encoding="utf-8")
    print(f"[video-remake] registered {len(rows)} project(s)")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    cmd = sys.argv[1]
    if cmd == "setup":
        setup()
    elif cmd == "create" and len(sys.argv) == 3:
        create(sys.argv[2])
    elif cmd == "register":
        register()
    else:
        sys.exit(__doc__)
